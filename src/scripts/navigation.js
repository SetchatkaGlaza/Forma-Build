import {$,$$,reduce} from './utils.js';
const nav=$('#nav'),burger=$('.burger'),hd=$('.header'),bar=$('.progress'),top=$('.top'),mbar=$('.mbar'),hero=$('.hero'),contact=$('#contact');
const setMenu=o=>{nav.classList.toggle('open',o);burger.setAttribute('aria-expanded',o);burger.setAttribute('aria-label',o?'Закрыть меню':'Открыть меню');hd.classList.remove('hide')};
burger.onclick=()=>setMenu(!nav.classList.contains('open'));
$$('a',nav).forEach(a=>a.onclick=()=>setMenu(false));
addEventListener('keydown',e=>{if(e.key==='Escape'&&nav.classList.contains('open')){setMenu(false);burger.focus()}});
hd.addEventListener('focusin',()=>hd.classList.remove('hide'));
const secs=$$('main section[id]'),links=$$('a[href^="#"]',nav);
let last=0,tick=false;
const onScroll=()=>{const y=scrollY,h=document.documentElement.scrollHeight-innerHeight;
 bar.style.width=(h>0?y/h*100:0)+'%';
 let id='';secs.forEach(s=>{if(s.offsetTop-140<=y)id=s.id});links.forEach(a=>a.classList.toggle('on',a.getAttribute('href')==='#'+id));
 const cs=secs.find(s=>s.offsetTop-72<=y&&s.offsetTop+s.offsetHeight-72>y);
 hd.classList.toggle('light',!!cs&&!cs.classList.contains('dark')&&!cs.classList.contains('hero'));
 hd.classList.toggle('hide',y>last&&y>400&&!nav.classList.contains('open'));last=y;
 top.classList.toggle('show',y>700);
 mbar.classList.toggle('show',y>innerHeight*.6&&contact.getBoundingClientRect().top>innerHeight*.9);
 if(!reduce&&y<innerHeight*1.2)hero.style.setProperty('--py',(y*.18).toFixed(1)+'px');
 tick=false};
addEventListener('scroll',()=>{if(!tick){tick=true;requestAnimationFrame(onScroll)}},{passive:true});onScroll();
top.onclick=()=>scrollTo({top:0,behavior:reduce?'auto':'smooth'});
